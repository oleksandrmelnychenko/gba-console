export function revenueRows(kind = 'known', selected = [0, 1, 2, 3]): SpreadsheetCellValue[][] {
  const all = structuredClone(fixtures[kind]), header = all.findIndex(row => row[0] === 'Клієнт' && row[1] === 'Договір')
  for (let i = 0; i < all.length; i += 1) {
    if (String(all[i][0]).startsWith('Показники:')) all[i] = ['Показники: ' + selected.map(m => REVENUE_COMPARISON_CAPTIONS[m]).join(', ')]
    if (i >= header - 1) all[i] = [...all[i].slice(0, 2), ...selected.map(m => all[i][m + 2] ?? null)]
  }
  return all
}
